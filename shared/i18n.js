let current = DEFAULT_LANG;

export function normalizeLang(value) {
	if (!value) return null;
	const base = String(value).trim().split("-")[0].toLowerCase();
	return LANGS.includes(base) ? base : null;
}

export const getLang = () => current;

function readCookie(name) {
	if (typeof document === "undefined") return null;
	const hit = document.cookie.split("; ").find((c) => c.startsWith(`${name}=`));
	return hit ? decodeURIComponent(hit.slice(name.length + 1)) : null;
}

function fromNavigator() {
	if (typeof navigator === "undefined") return null;
	for (const tag of navigator.languages ?? [navigator.language]) {
		const match = normalizeLang(tag);
		if (match) return match;
	}
	return null;
}

export function initLang(explicit) {
	current =
		normalizeLang(explicit) ??
		normalizeLang(typeof document !== "undefined" ? document.documentElement.dataset.lang : null) ??
		normalizeLang(readCookie("lang")) ??
		fromNavigator() ??
		DEFAULT_LANG;
	if (typeof document !== "undefined") {
		document.documentElement.lang = current;
		document.documentElement.dataset.lang = current;
	}
	return current;
}

export function setLang(next, { reload = true } = {}) {
	const lang = normalizeLang(next);
	if (!lang || lang === current) return current;
	current = lang;
	if (typeof document !== "undefined") {
		document.cookie = `lang=${lang}; path=/; max-age=31536000; samesite=lax`;
		document.documentElement.lang = lang;
		document.documentElement.dataset.lang = lang;
	}
	if (reload && typeof location !== "undefined") location.reload();
	else applyTranslations();
	return lang;
}

const pluralRules = new Map();

function pluralForm(lang, count) {
	if (!pluralRules.has(lang)) pluralRules.set(lang, new Intl.PluralRules(lang));
	return pluralRules.get(lang).select(count);
}

const lookup = (lang, key) => STRINGS[lang]?.[key] ?? STRINGS[DEFAULT_LANG][key];

/** Stateless form, for the server — it handles every language at once. */
export function translate(lang, key, vars) {
	const use = normalizeLang(lang) ?? DEFAULT_LANG;
	let template;
	if (vars && typeof vars.count === "number") {
		template =
			lookup(use, `${key}.${pluralForm(use, vars.count)}`) ??
			lookup(use, `${key}.other`) ??
			lookup(use, key);
	} else {
		template = lookup(use, key);
	}
	if (template === undefined) return key;
	if (!vars) return template;
	return template.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole));
}

export const t = (key, vars) => translate(current, key, vars);

export function applyTranslations(root = document) {
	for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
	for (const node of root.querySelectorAll("[data-i18n-html]")) node.innerHTML = t(node.dataset.i18nHtml);
	for (const node of root.querySelectorAll("[data-i18n-attr]")) {
		for (const pair of node.dataset.i18nAttr.split(";")) {
			const [attr, key] = pair.split(":");
			if (attr && key) node.setAttribute(attr.trim(), t(key.trim()));
		}
	}
}

export const numberFormat = (options) => new Intl.NumberFormat(current, options);
export const dateFormat = (options) => new Intl.DateTimeFormat(current, options);
